/* Runs in the browser, with the raw draw.io SVG as the document's only content. */
async function transform(cfg) {
  const NS = 'http://www.w3.org/2000/svg';
  const XLINK = 'http://www.w3.org/1999/xlink';
  const root = document.querySelector('svg');
  const origin = root.getBoundingClientRect();
  const parse = (markup) => {
    const holder = document.createElementNS(NS, 'g');
    holder.innerHTML = markup.replaceAll('{p}', cfg.prefix);
    return holder.firstElementChild;
  };
  const cell = (id) => root.querySelector(`[data-cell-id="${id}"]`);
  const box = (el) => {
    const r = el.getBoundingClientRect();
    return { x: r.left - origin.left, y: r.top - origin.top, w: r.width, h: r.height };
  };
  const round = (n) => +n.toFixed(2);

  // 1. Replace each foreignObject (and its <switch> PNG fallback) with native SVG.
  const flatten = (fo) => {
    const parts = [];
    const math = fo.querySelector('mjx-container svg');
    if (math) {
      const b = box(math);
      const nested = math.cloneNode(true);
      nested.removeAttribute('style');
      for (const [k, v] of [['x', b.x], ['y', b.y], ['width', b.w], ['height', b.h]]) nested.setAttribute(k, round(v));
      nested.setAttribute('overflow', 'visible');
      nested.setAttribute('color', '#000');
      parts.push(nested);
    } else {
      const walker = document.createTreeWalker(fo, NodeFilter.SHOW_TEXT);
      while (walker.nextNode()) {
        const node = walker.currentNode;
        const str = node.textContent.trim();
        if (!str) continue;
        const range = document.createRange();
        range.selectNodeContents(node);
        if (range.getClientRects().length > 1) throw new Error(`label wraps: "${str}"`);
        const b = box(range);
        const css = getComputedStyle(node.parentElement);
        const text = document.createElementNS(NS, 'text');
        const attrs = {
          x: round(b.x + b.w / 2), y: round(b.y + b.h / 2), 'font-family': 'Helvetica, Arial, sans-serif',
          'font-size': css.fontSize.replace('px', ''), 'font-weight': css.fontWeight, fill: css.color,
          'text-anchor': 'middle', 'dominant-baseline': 'central',
        };
        for (const k in attrs) text.setAttribute(k, attrs[k]);
        text.textContent = str;
        parts.push(text);
      }
    }
    return parts;
  };
  const equationRows = [];
  for (const fo of [...root.querySelectorAll('foreignObject')]) {
    const parts = flatten(fo);
    const rows = fo.querySelectorAll('[data-mml-node="mtr"]');
    if (rows.length) {
      rows.forEach((r, i) => equationRows.push({ name: cfg.equations.rows[i], box: box(r) }));
      const copied = parts[0].querySelectorAll('[data-mml-node="mtr"]');
      copied.forEach((r, i) => {
        r.setAttribute('class', 'flow-block');
        r.setAttribute('data-block', cfg.equations.rows[i]);
      });
    }
    fo.closest('switch').replaceWith(...parts);
  }

  // 2. Equation highlights sit behind the rows; rows were measured before the swap above.
  const eqCell = cell(cfg.equations.cell);
  const eqGroup = document.createElementNS(NS, 'g');
  eqGroup.setAttribute('id', `${cfg.prefix}-equations`);
  eqCell.replaceWith(eqGroup);
  for (const r of equationRows) {
    const hl = document.createElementNS(NS, 'rect');
    const attrs = {
      id: `${cfg.prefix}-${r.name}-hl`, class: 'flow-block flow-eq-hl', 'data-block': r.name,
      x: round(r.box.x - 3), y: round(r.box.y - 1.5), width: round(r.box.w + 6), height: round(r.box.h + 3), rx: 2.5,
    };
    for (const k in attrs) hl.setAttribute(k, attrs[k]);
    eqGroup.appendChild(hl);
  }
  eqGroup.append(...eqCell.querySelectorAll('svg'));

  // 3. Name blocks and arrows, then add what the source does not draw.
  for (const id of cfg.remove) cell(id).remove();
  for (const [id, [name, block, flag]] of Object.entries(cfg.cells)) {
    const g = cell(id);
    const target = flag === 'text-only' ? g.querySelector('text') : g;
    g.setAttribute('id', `${cfg.prefix}-${name}`);
    target.setAttribute('class', flag === 'flame' ? 'flow-block flow-flame' : 'flow-block');
    target.setAttribute('data-block', block);
    if (flag === 'shape') g.querySelector('rect, ellipse').classList.add('flow-shape');
  }
  for (const [id, name] of Object.entries(cfg.edges)) {
    const g = cell(id);
    const [line, head] = g.querySelectorAll('path');
    g.setAttribute('id', `${cfg.prefix}-edge-${name}`);
    g.setAttribute('data-edge', name);
    line.setAttribute('class', 'flow-line');
    head.setAttribute('class', 'flow-head');
  }
  const layer = cell('1');
  for (const [name, d] of Object.entries(cfg.add.edges)) {
    layer.appendChild(parse(`<g id="{p}-edge-${name}" data-edge="${name}">
      <path class="flow-line" d="${d}" fill="none" stroke="#000" stroke-miterlimit="10"/>
      <path class="flow-head" fill="#000" stroke="#000" stroke-miterlimit="10"/></g>`));
  }
  for (const markup of cfg.add.blocks) layer.appendChild(parse(markup));
  cell(cfg.panel).setAttribute('id', `${cfg.prefix}-panel`);

  // 4. Shrink embedded images: photos to JPEG, anything with transparency stays PNG.
  const shrink = async (image) => {
    const href = image.getAttributeNS(XLINK, 'href') || image.getAttribute('href');
    const img = new Image();
    img.src = href;
    await img.decode();
    const inSymbol = !!image.closest('symbol');
    const maxW = inSymbol ? 128 : 360;
    const scale = Math.min(1, maxW / img.naturalWidth);
    const canvas = document.createElement('canvas');
    canvas.width = Math.round(img.naturalWidth * scale);
    canvas.height = Math.round(img.naturalHeight * scale);
    canvas.getContext('2d').drawImage(img, 0, 0, canvas.width, canvas.height);
    image.removeAttribute('href');
    image.setAttributeNS(XLINK, 'href', inSymbol ? canvas.toDataURL('image/png') : canvas.toDataURL('image/jpeg', 0.85));
  };
  for (const image of root.querySelectorAll('image')) await shrink(image);

  // 5. Drop draw.io's light/dark colours (the presentation attributes hold the light values).
  root.querySelector('style')?.remove();
  for (const el of root.querySelectorAll('[style]')) {
    const kept = el.getAttribute('style').split(';').map((s) => s.trim())
      .filter((s) => s && !s.includes('light-dark') && !s.includes('var(--ge'));
    if (kept.length) el.setAttribute('style', kept.join('; '));
    else el.removeAttribute('style');
  }
  for (const el of root.querySelectorAll('[pointer-events]')) el.removeAttribute('pointer-events');
  for (const el of root.querySelectorAll('[data-cell-id]')) el.removeAttribute('data-cell-id');
  for (const el of root.querySelectorAll('[role], [focusable]')) { el.removeAttribute('role'); el.removeAttribute('focusable'); }

  // 6. Namespace ids so several figures can be inlined in one page. Duplicates are identical clip paths.
  const seen = new Set();
  const internal = [...root.querySelectorAll('[id]')].filter((el) => !el.id.startsWith(`${cfg.prefix}-`));
  for (const el of internal) {
    if (seen.has(el.id)) { el.remove(); continue; }
    seen.add(el.id);
    el.id = `${cfg.prefix}-${el.id}`;
  }
  for (const el of root.querySelectorAll('*')) {
    for (const attr of [...el.attributes]) {
      if (attr.value.startsWith('#') && (attr.localName === 'href') && seen.has(attr.value.slice(1))) {
        attr.value = `#${cfg.prefix}-${attr.value.slice(1)}`;
      } else if (attr.value.includes('url(#')) {
        attr.value = attr.value.replace(/url\(#([^)]+)\)/g, (m, id) => (seen.has(id) ? `url(#${cfg.prefix}-${id})` : m));
      }
    }
  }

  // 7. Root element: crop, and let the page size it.
  for (const a of ['width', 'height', 'style', 'id']) root.removeAttribute(a);
  root.setAttribute('viewBox', cfg.viewBox);
  root.setAttribute('class', 'flow-svg');
  return new XMLSerializer().serializeToString(root);
}

(async () => {
  const name = process.argv[2];
  const cfg = FIGURES[name];
  if (!cfg) throw new Error(`Usage: build.js <${Object.keys(FIGURES).join('|')}>`);
  const raw = fs.readFileSync(path.join(ROOT, cfg.src), 'utf8').replace(/^<\?xml[^>]*>\s*<!DOCTYPE[^>]*>\s*/, '');
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 800 }, colorScheme: 'light' });
  await page.setContent(`<!doctype html><body style="margin:0"><div>${raw}</div></body>`);
  const svg = await page.evaluate(transform, cfg);
  await browser.close();
  const out = path.join(ROOT, cfg.out);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, svg);
  console.log(`${cfg.out}: ${(svg.length / 1024).toFixed(0)} KB (source ${(raw.length / 1024).toFixed(0)} KB)`);
})();

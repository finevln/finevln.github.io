//   - names each cell with an id and the block it belongs to, so the page can dim or highlight it
//   - replaces <foreignObject> labels with native SVG (Safari misrenders them under opacity/filter)
//   - shrinks embedded images, drops draw.io's dark-mode colours, and namespaces every id
//   - adds the blocks and arrows the source does not draw (listed under `add`)
//
// Usage (Playwright is a dev-only tool, so install it outside the repo):
//   NODE_PATH=<dir>/node_modules node tools/flow-figures/build.js implicit
